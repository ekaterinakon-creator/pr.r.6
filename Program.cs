                        Console.Write("Введите 3-ю сторону 1-го треугольника: "); // ввод переменной c
                        c = Convert.ToDouble(Console.ReadLine()); // преобразование в вещественный тип
                        Console.Write("\nВведите 1-ю сторону 2-го треугольника: "); // ввод переменной d
                        d = Convert.ToDouble(Console.ReadLine()); // преобразование в вещественный тип
                        Console.Write("Введите 2-ю сторону 2-го треугольника: "); // ввод переменной e
                        e = Convert.ToDouble(Console.ReadLine()); // преобразование в вещественный тип
                        Console.Write("Введите 3-ю сторону 2-го треугольника: "); // ввод переменной f
                        f = Convert.ToDouble(Console.ReadLine()); break; // преобразование в вещественный тип

                    case 2: // если пользователь сделал выбор 2
                        Console.WriteLine("вы выбрали начать с 2-го треугольника");  // вывод выбора пользователя

                        Console.Write("Введите 1-ю сторону 2-го треугольника: "); // ввод переменной a
                        d = Convert.ToDouble(Console.ReadLine()); // преобразование в вещественный тип
                        Console.Write("Введите 2-ю сторону 2-го треугольника: "); // ввод переменной b
                        e = Convert.ToDouble(Console.ReadLine()); // преобразование в вещественный тип
                        Console.Write("Введите 3-ю сторону 2-го треугольника: "); // ввод переменной c
                        f = Convert.ToDouble(Console.ReadLine()); // преобразование в вещественный тип
                        Console.Write("\nВведите 1-ю сторону 1-го треугольника: "); // ввод переменной d
                        a = Convert.ToDouble(Console.ReadLine()); // преобразование в вещественный тип
                        Console.Write("Введите 2-ю сторону 1-го треугольника: "); // ввод переменной e
