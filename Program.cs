        static void Main(string[] args)
        {
            Console.Title = "Практическая работа №5";
            double a=0, b=0, c=0, d=0, e=0, f=0; // объявление тип данных
            double s1=0, s2=0, p1=0, p2=0;   // объявление тип данных
            int choice=0; // объявление тип данных

